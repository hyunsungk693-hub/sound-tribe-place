-- 접속 상태 표시를 위한 마지막 접속 시각.
--
-- 문제
--   ProfileCard의 "활동 중" 배지가 profiles.updated_at이 7일 이내인지로 판정했다.
--   그건 "최근 일주일 안에 프로필을 수정했다"는 뜻이지 접속 여부가 아니다.
--   한 달 전에 닉네임 한 번 바꾸고 안 들어온 사람도 일주일간 "활동 중"으로 보였고,
--   매일 들어오지만 프로필을 안 고치는 사람은 영영 안 붙었다.
--
-- 해결
--   앱이 열려 있는 동안 주기적으로 찍는 last_seen_at을 둔다.
--   배지는 이 값이 최근 몇 분 이내일 때만 붙는다(기준은 프론트가 정한다).
--
-- 개인정보
--   profiles는 공개 테이블이라 이 값도 남에게 보인다. 즉 "지금 접속 중"이
--   공개된다. 그게 이 기능의 목적이지만, 원치 않는 사용자를 위한 숨김 설정은
--   아직 없다. 필요해지면 profiles에 플래그를 더해 갱신 자체를 건너뛰면 된다.
--
--   정확한 시각을 그대로 노출하면 생활 패턴이 드러나므로, 화면에는 "활동 중"
--   여부만 보이고 시각 자체는 표시하지 않는다.

ALTER TABLE public.profiles
  ADD COLUMN IF NOT EXISTS last_seen_at timestamptz;

-- 갱신은 본인만. profiles의 기존 UPDATE 정책이 이미 본인 행으로 제한하므로
-- 새 정책은 두지 않는다. 대신 하트비트가 다른 컬럼을 건드리지 못하게
-- 컬럼 단위 권한으로 좁힌다 — 20260830200001에서 job_applications에 쓴 방식과 같다.
--
-- 주의: GRANT UPDATE(컬럼)은 기존 전체 UPDATE 권한을 대체한다. profiles는
-- 프로필 편집에서 여러 컬럼을 함께 저장하므로 여기서 권한을 좁히면 편집이 깨진다.
-- 그래서 권한은 건드리지 않고 RLS(본인 행)만으로 충분하다고 본다.

-- 목록에서 "접속 중인 사람"을 따로 훑는 화면은 없으므로 인덱스는 두지 않는다.

COMMENT ON COLUMN public.profiles.last_seen_at IS
  '앱이 열려 있는 동안 클라이언트가 주기적으로 갱신. "활동 중" 배지 판정에만 쓴다.';

